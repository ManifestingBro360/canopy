// `canopy demo`: builds a throwaway repository, starts canopyd on it, and plays
// scripted agents against the real hook endpoint and the real landing gate.
// The agents are scripts, not models. Everything else is the real system.
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { execFileSync } from 'node:child_process';

const LAYOUT = {
  lib: ['money', 'dates', 'ids', 'text', 'retry', 'cache', 'log'],
  billing: ['invoice', 'charge', 'tax', 'ledger', 'policy'],
  catalog: ['cart', 'product', 'pricing', 'inventory', 'search'],
  auth: ['session', 'tokens', 'roles', 'password'],
  api: ['orders', 'users', 'payments', 'webhooks', 'health', 'admin'],
  'web/components': ['Cart', 'Checkout', 'Nav', 'Receipt', 'Login', 'Table', 'Banner'],
  'web/pages': ['home', 'order', 'account'],
  jobs: ['nightly', 'emails', 'cleanup'],
};
const LIB_FNS = { money: ['toCents', 'fromCents', 'roundHalf'], dates: ['addDays', 'startOfDay'], ids: ['newId', 'shortId'], text: ['slug', 'truncate'], retry: ['backoff'], cache: ['memo', 'ttl'], log: ['level'] };
const TARGETS = [['lib/money.js', 'toCents'], ['lib/dates.js', 'addDays'], ['lib/text.js', 'slug']];

let seed = 7;
const rnd = () => ((seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
const pick = (a) => a[Math.floor(rnd() * a.length)];
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function generate(root) {
  const w = (p, s) => { mkdirSync(dirname(join(root, p)), { recursive: true }); writeFileSync(join(root, p), s); };
  for (const [mod, fns] of Object.entries(LIB_FNS)) {
    w(`lib/${mod}.js`, fns.map((f, i) => `export function ${f}(v) {\n  const k = ${i + 2};\n  return Math.round(v * k) + ${fns.length};\n}\n`).join('\n'));
  }
  const libPairs = Object.entries(LIB_FNS).flatMap(([m, fns]) => fns.map((f) => [m, f]));
  for (const [dir, files] of Object.entries(LAYOUT)) {
    if (dir === 'lib') continue;
    const up = '../'.repeat(dir.split('/').length);
    for (const name of files) {
      const uses = new Map();
      const n = 2 + Math.floor(rnd() * 4);
      // The protected file must not call a function the demo changes, or every cycle would wait for a person.
      const pool = dir === 'auth' && name === 'session' ? libPairs.filter(([, f]) => !TARGETS.some((t) => t[1] === f)) : libPairs;
      while (uses.size < 3) { const [m, f] = pick(pool); uses.set(f, m); }
      const used = [...uses.keys()];
      const byMod = new Map();
      for (const [f, m] of uses) byMod.set(m, [...(byMod.get(m) || []), f]);
      let src = [...byMod].map(([m, fs]) => `import { ${fs.join(', ')} } from '${up}lib/${m}.js';`).join('\n') + '\n\n';
      const mine = [];
      for (let i = 0; i < n; i++) {
        const fn = name.charAt(0).toLowerCase() + name.slice(1) + ['Total', 'Check', 'Build', 'Load', 'Apply', 'Format'][i];
        mine.push(fn);
        const pad = Array.from({ length: 2 + Math.floor(rnd() * 14) }, (_, j) => `  x = x + ${j + 1};`).join('\n');
        src += `export function ${fn}(v) {\n  let x = ${pick(used)}(v);\n${pad}\n  const y = ${pick(used)}(x);\n  return x + y;\n}\n\n`;
      }
      src += `export function selfTest() {\n  return ${mine.map((f) => `${f}(3)`).join(' + ')};\n}\n`;
      w(`${dir}/${name}.js`, src);
    }
  }
  w('tests/run.js', `import { readdirSync, statSync } from 'node:fs';
import { join } from 'node:path';
const walk = (d) => readdirSync(d).flatMap((f) => { const p = join(d, f); return statSync(p).isDirectory() ? walk(p) : [p]; });
let n = 0;
for (const dir of ${JSON.stringify(Object.keys(LAYOUT))}) for (const f of walk(dir)) {
  const m = await import(new URL('../' + f, import.meta.url));
  if (m.selfTest) { const r = m.selfTest(); if (!Number.isFinite(r)) { console.error('selfTest failed in ' + f); process.exit(1); } n++; }
}
console.log('ok', n);
`);
  w('.canopy/rules.json', JSON.stringify({ version: 1, rules: [
    { path: '', checks: ['node tests/run.js'] },
    { path: 'lib/', min_coverage: 0.3 },
    { path: 'auth/', no_tainted: true },
    { path: 'auth/session.js', protected: true },
  ] }, null, 2) + '\n');
  w('README.md', '# demo shop\n\nGenerated by `canopy demo`.\n');
}

export async function runDemo({ port, once, fast }) {
  const pace = fast ? 60 : 1100;
  const base = mkdtempSync(join(tmpdir(), 'canopy-demo-'));
  const repo = join(base, 'shop');
  const env = { ...process.env, GIT_AUTHOR_NAME: 'demo', GIT_AUTHOR_EMAIL: 'demo@localhost', GIT_COMMITTER_NAME: 'demo', GIT_COMMITTER_EMAIL: 'demo@localhost' };
  const git = (cwd, ...a) => execFileSync('git', a, { cwd, env, encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] }).trim();
  mkdirSync(repo, { recursive: true });
  git(repo, 'init', '-q', '-b', 'main');
  generate(repo);
  git(repo, 'add', '-A'); git(repo, 'commit', '-qm', 'Generated demo shop');
  process.env.CANOPY_HOME = join(base, 'canopy-home');
  const { serve } = await import('../src/server.mjs');
  const d = await serve({ cwd: repo, port });
  console.log(`\ndemo repo ${repo}\nopen     http://127.0.0.1:${d.port}\n`);
  const url = `http://127.0.0.1:${d.port}`;
  const post = async (path, body) => (await fetch(url + path, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) })).json();

  let sid = 0;
  const agent = (branch, task) => {
    const wt = join(base, 'wt', branch.replace(/\//g, '-'));
    git(repo, 'worktree', 'add', '-q', wt, '-b', branch);
    const a = { wt, branch, session: `demo-${++sid}-${branch}` };
    const hook = (ev, tool, input, extra = {}) => post('/hook', { session_id: a.session, cwd: wt, hook_event_name: ev, tool_name: tool, tool_input: input || {}, ...extra });
    a.start = async () => { await hook('SessionStart'); await hook('UserPromptSubmit', '', {}, { prompt: task }); };
    a.read = (p) => hook('PostToolUse', 'Read', { file_path: join(wt, p) });
    a.edit = async (p, fn) => {
      const cur = existsSync(join(wt, p)) ? readFileSync(join(wt, p), 'utf8') : '';
      const next = fn(cur);
      const pre = await hook('PreToolUse', cur ? 'Edit' : 'Write', cur ? { file_path: join(wt, p), old_string: firstDiffLine(cur, next) } : { file_path: join(wt, p) });
      const denied = pre.hookSpecificOutput && pre.hookSpecificOutput.permissionDecision === 'deny';
      if (denied) return { denied: true };
      mkdirSync(dirname(join(wt, p)), { recursive: true });
      writeFileSync(join(wt, p), next);
      await hook('PostToolUse', cur ? 'Edit' : 'Write', { file_path: join(wt, p) });
      return { denied: false };
    };
    a.shell = async (cmd, fn) => { fn(); await hook('PostToolUse', 'Bash', { command: cmd }); await sleep(250); };
    a.fetch = (u) => hook('PostToolUse', 'WebFetch', { url: u });
    a.commit = (m) => { git(wt, 'add', '-A'); if (git(wt, 'status', '--porcelain')) git(wt, 'commit', '-qm', m); };
    a.land = async () => { const r = await post('/api/land', { cwd: wt, intent: task }); console.log(`  ${branch.padEnd(26)} ${r.status}${r.reasons && r.reasons.length ? ' - ' + r.reasons[0].split('\n')[0].slice(0, 110) : ''}`); return r; };
    a.done = async () => { await hook('SessionEnd'); await post('/api/release', { cwd: wt }); try { git(repo, 'worktree', 'remove', '--force', wt); } catch { /* already gone */ } };
    return a;
  };
  const firstDiffLine = (a, b) => { const A = a.split('\n'), B = new Set(b.split('\n')); return A.find((l) => l.trim() && !B.has(l)) || A.find((l) => l.trim()) || ''; };
  const tweak = (fnName) => (src) => src.replace(new RegExp(`(export function ${fnName}\\(v[^)]*\\) \\{\\n)`), `$1  // tuned ${Date.now() % 100000}\n`);

  for (let c = 1; ; c++) {
    const [libFile, fn] = TARGETS[(c - 1) % TARGETS.length];
    console.log(`cycle ${c}: ${fn} gains a required argument`);
    const callers = [...new Set([...(d.engine.graph.rdeps.get(`${libFile}#${fn}`) || [])].map((n) => n.split('#')[0]))].filter((p) => p !== libFile && !p.startsWith('tests/'));
    const A = agent(`feat/${fn}-mode-${c}`, `Add a required mode argument to ${fn} and update its callers`);
    const B = agent(`feat/settlement-report-${c}`, 'Add a nightly settlement report job');
    const C = agent(`fix/cart-rounding-${c}`, 'Fix rounding in cart totals');
    const E = agent(`chore/format-nav-${c}`, 'Reformat the navigation component');
    for (const a of [A, B, C, E]) await a.start();
    await sleep(pace);
    await A.read(libFile); for (const p of callers.slice(0, 3)) { await A.read(p); await sleep(pace / 3); }
    await B.read(libFile); await B.read('jobs/nightly.js'); await C.read('catalog/cart.js'); await C.read(libFile); await E.read('web/components/Nav.js');
    await sleep(pace);
    // A changes the signature. B and C read that function, so both are told while they work.
    await A.edit(libFile, (s) => s.replace(new RegExp(`export function ${fn}\\(([^)]*)\\) \\{`), `export function ${fn}($1, m${c}) {\n  if (m${c} === undefined) throw new Error('${fn}: m${c} is required');`));
    await sleep(pace);
    await B.read('jobs/emails.js');
    const sample = new RegExp(`\\b${fn}\\(([^()]*)\\)`).exec(readFileSync(join(repo, callers[0]), 'utf8'));
    const oldArgs = ['v', ...sample[1].split(',').slice(1).map((x) => x.trim())].join(', ');
    // B writes new code against the signature that is on main: a clean text merge, but wrong once A lands.
    await B.edit(`jobs/report${c}.js`, () => `import { ${fn} } from '../${libFile}';\n\nexport function settlementReport${c}(v) {\n  return ${fn}(${oldArgs}) + 1;\n}\n\nexport function selfTest() {\n  return settlementReport${c}(3);\n}\n`);
    await sleep(pace);
    const tried = await B.edit(libFile, tweak(fn));
    console.log(`  ${B.branch.padEnd(26)} edit of ${fn} while A holds it: ${tried.denied ? 'refused, told to wait' : 'allowed'}`);
    await sleep(pace);
    await C.edit('catalog/cart.js', tweak('cartTotal')); C.commit('Fix rounding in cart totals'); await C.land();
    await sleep(pace);
    await E.shell("sed -i '' 's/x = x + 1;/x += 1;/' web/components/Nav.js", () => {
      const p = join(E.wt, 'web/components/Nav.js'), t = readFileSync(p, 'utf8');
      writeFileSync(p, t.includes('x += 1;') ? t.replace(/x \+= 1;/g, 'x = x + 1;') : t.replace(/x = x \+ 1;/g, 'x += 1;'));
    });
    E.commit('Reformat the navigation component'); await E.land();
    await sleep(pace);
    for (const p of callers) {
      await A.read(p);
      await A.edit(p, (s) => s.split('\n').map((l) => (l.startsWith('export function') ? l : l.replace(new RegExp(`\\b${fn}\\(([^()]*)\\)`, 'g'), `${fn}($1, ${c})`))).join('\n'));
      await sleep(pace / 4);
    }
    A.commit(`${fn} takes a required mode argument`); await A.land();
    await sleep(pace);
    await B.read('jobs/cleanup.js');
    B.commit('Add settlement report job');
    const first = await B.land();
    await sleep(pace);
    if (first.status !== 'landed') {
      git(B.wt, 'merge', '-q', 'main', '-m', 'Merge main');
      await B.read(libFile);
      await B.edit(`jobs/report${c}.js`, (s) => s.replace(new RegExp(`\\b${fn}\\(([^()]*)\\)`), `${fn}($1, ${c})`));
      B.commit('Pass the new mode argument'); await B.land();
    }
    if (c === 1) {
      const D = agent('chore/session-timeout', 'Raise the session timeout as the vendor docs recommend');
      await D.start(); await D.fetch('https://docs.example.com/sessions'); await D.read('auth/session.js');
      await D.edit('auth/session.js', tweak('sessionTotal')); D.commit('Raise session timeout'); await D.land();
    }
    for (const a of [A, B, C, E]) await a.done();
    if (once) { const st = await (await fetch(url + '/api/stats')).json(); console.log(`\nhooks ${st.hooks}, p50 ${st.hook_ms_p50} ms, p95 ${st.hook_ms_p95} ms`); d.server.close(); return; }
    await sleep(pace * 5);
  }
}
